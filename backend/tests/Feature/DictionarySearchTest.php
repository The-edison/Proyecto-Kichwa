    public function test_direction_accents_prefix_priority_and_only_dictionary_fields_are_returned(): void
    {
        Diccionario::create(['kichwa' => 'xábc', 'español' => 'Otra entrada técnica']);
        $first = Diccionario::create(['kichwa' => 'Ábc inicial', 'español' => 'Éxito técnico']);
        $this->getJson('/api/diccionario/buscar?q=ABC&direccion=kichwa-es')->assertOk()->assertJsonPath('total', 2)->assertJsonPath('data.0', ['id' => $first->id, 'kichwa' => 'Ábc inicial', 'español' => 'Éxito técnico']);
        $this->getJson('/api/diccionario/buscar?q=exito&direccion=es-kichwa')->assertOk()->assertJsonPath('total', 1)->assertJsonPath('data.0.kichwa', 'Ábc inicial');
        $this->getJson('/api/diccionario/buscar?q=%25&direccion=es-kichwa')->assertOk()->assertJsonPath('total', 0);
        $this->getJson('/api/diccionario/buscar?q=x&direccion=invalid')->assertUnprocessable()->assertJsonValidationErrors('direccion');
    }

