    public function test_migration_preserves_translations_and_unifies_legacy_entries(): void
    {
        Schema::drop('diccionario');
        $original = require database_path('migrations/2026_09_30_000014_create_diccionario_table.php');
        $original->up();
        DB::statement('ALTER TABLE diccionario ADD COLUMN sinonimos_diccionario text, ADD COLUMN notas_diccionario text');
        DB::table('diccionario')->insert(['palabra_kichwa_diccionario' => '[DEMO] original', 'palabra_espanol_diccionario' => 'Traducción original', 'notas_diccionario' => 'Retirar']);
        $id = DB::table('diccionario')->value('id_diccionario');
        DB::statement('CREATE TABLE glossary (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, kichwa varchar(160), spanish varchar(160))');
        DB::table('glossary')->insert([
            ['kichwa' => '[DEMO] original', 'spanish' => 'Traducción original'],
            ['kichwa' => '[DEMO] anterior', 'spanish' => 'Traducción anterior'],
        ]);

        $migration = require database_path('migrations/2026_10_06_163017_simplify_diccionario_and_remove_legacy_glossary.php');
        $migration->up();

        $this->assertSame(['id', 'kichwa', 'español'], Schema::getColumnListing('diccionario'));
        $this->assertFalse(Schema::hasTable('glossary'));
        $this->assertDatabaseCount('diccionario', 2);
        $this->assertDatabaseHas('diccionario', ['id' => $id, 'kichwa' => '[DEMO] original', 'español' => 'Traducción original']);
        $this->assertDatabaseHas('diccionario', ['kichwa' => '[DEMO] anterior', 'español' => 'Traducción anterior']);
    }

    public function test_admin_can_create_edit_list_and_delete_three_field_entries(): void
    {
        $this->postJson('/api/admin/diccionario', ['kichwa' => '[DEMO] entrada', 'español' => 'Traducción'])->assertUnauthorized();
        Sanctum::actingAs(Usuario::factory()->create());
        $this->postJson('/api/admin/diccionario', ['kichwa' => '[DEMO] entrada', 'español' => 'Traducción'])->assertForbidden();
        Sanctum::actingAs(Usuario::factory()->administrador()->create());
        $this->postJson('/api/admin/diccionario', ['kichwa' => ''])->assertUnprocessable()->assertJsonValidationErrors(['kichwa', 'español']);
        $response = $this->postJson('/api/admin/diccionario', ['kichwa' => '[DEMO] entrada', 'español' => 'Traducción', 'id' => 999999, 'notes' => 'No guardar'])->assertCreated();
        $id = $response->json('id');
        $this->assertNotSame(999999, $id);
        $response->assertExactJson(['id' => $id, 'kichwa' => '[DEMO] entrada', 'español' => 'Traducción']);
        $this->assertDatabaseHas('diccionario', ['id' => $id, 'kichwa' => '[DEMO] entrada', 'español' => 'Traducción']);
        $this->getJson('/api/admin/overview')->assertOk()->assertJsonPath('diccionario', 1)->assertJsonMissingPath('glossary');
        $this->getJson('/api/admin/diccionario')->assertOk()->assertJsonPath('data.0', ['id' => $id, 'kichwa' => '[DEMO] entrada', 'español' => 'Traducción']);
        $this->patchJson('/api/admin/diccionario/'.$id, ['español' => 'Corregida'])->assertOk()->assertExactJson(['id' => $id, 'kichwa' => '[DEMO] entrada', 'español' => 'Corregida']);
        $this->assertDatabaseHas('diccionario', ['id' => $id, 'español' => 'Corregida']);
        $this->postJson('/api/admin/diccionario', ['kichwa' => '[DEMO] entrada', 'español' => 'Corregida'])->assertUnprocessable()->assertJsonValidationErrors('kichwa');
        $this->deleteJson('/api/admin/diccionario/'.$id)->assertNoContent();
        $this->assertDatabaseMissing('diccionario', ['id' => $id]);
    }

