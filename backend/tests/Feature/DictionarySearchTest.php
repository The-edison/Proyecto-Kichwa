    public function test_spanish_search_ranks_individual_dictionary_meanings_before_related_phrases_and_substrings(string $word, array $definitions, array $expected): void
    {
        foreach ($definitions as [$kichwa, $spanish]) {
            Diccionario::create(['kichwa' => $kichwa, 'español' => $spanish]);
        }

        $response = $this->getJson('/api/diccionario/buscar?'.http_build_query(['q' => $word, 'direccion' => 'es-kichwa']))->assertOk();

        $this->assertSame($expected, array_column($response->json('data'), 'kichwa'));
    }

    public function test_spanish_exact_meaning_is_on_first_page_even_after_many_related_entries(): void
    {
        foreach (range(1, 25) as $index) {
            Diccionario::create(['kichwa' => 'relacionada '.$index, 'español' => 's. agua termal.']);
        }
        $exact = Diccionario::create(['kichwa' => 'yaku', 'español' => 's. agua, líquido; s. octubre.']);

        $first = $this->getJson('/api/diccionario/buscar?q=agua&direccion=es-kichwa')->assertOk()->assertJsonPath('total', 26)->assertJsonPath('data.0.id', $exact->id);
        $second = $this->getJson('/api/diccionario/buscar?q=agua&direccion=es-kichwa&page=2')->assertOk()->assertJsonCount(6, 'data');

        $ids = array_merge(array_column($first->json('data'), 'id'), array_column($second->json('data'), 'id'));
        $this->assertCount(26, array_unique($ids));
    }

    #[TestWith(['kichwa-es', 'kichwa', 'español'])]
    #[TestWith(['es-kichwa', 'español', 'kichwa'])]
    public function test_exact_matches_come_first_and_similarity_outweighs_prefix_position(string $direction, string $source, string $target): void
    {
        $entries = [];
        foreach (['a abc expresión larga adicional', 'abc a expresión larga adicional', 'xabc', 'abc z', '  Ábc  '] as $index => $word) {
            $entries[$word] = Diccionario::create([$source => $word, $target => 'Traducción '.$index]);
        }

        $response = $this->getJson('/api/diccionario/buscar?'.http_build_query(['q' => '  ABC  ', 'direccion' => $direction]))->assertOk()->assertJsonPath('total', 5);

        $this->assertSame([
            $entries['  Ábc  ']->id,
            $entries['abc z']->id,
            ...($direction === 'kichwa-es' ? [$entries['xabc']->id] : []),
            $entries['abc a expresión larga adicional']->id,
            $entries['a abc expresión larga adicional']->id,
            ...($direction === 'es-kichwa' ? [$entries['xabc']->id] : []),
        ], array_column($response->json('data'), 'id'));
        $response->assertJsonPath('data.0.'.$target, 'Traducción 4');
    }

    #[TestWith(['kichwa-es', 'kichwa', 'español'])]
    #[TestWith(['es-kichwa', 'español', 'kichwa'])]
    public function test_exact_match_stays_on_first_page_and_equal_matches_paginate_stably(string $direction, string $source, string $target): void
    {
        $prefixes = [];
        foreach (range(1, 25) as $index) {
            $prefixes[] = Diccionario::create([$source => 'abc similar', $target => 'Traducción '.$index])->id;
        }
        $exact = Diccionario::create([$source => 'Ábc', $target => 'Exacta']);

        $first = $this->getJson('/api/diccionario/buscar?q=abc&direccion='.$direction)->assertOk()->assertJsonPath('total', 26)->assertJsonPath('last_page', 2)->assertJsonPath('data.0.id', $exact->id);
        $second = $this->getJson('/api/diccionario/buscar?q=abc&direccion='.$direction.'&page=2')->assertOk()->assertJsonCount(6, 'data');

        $this->assertSame(array_merge([$exact->id], $prefixes), array_merge(array_column($first->json('data'), 'id'), array_column($second->json('data'), 'id')));
    }

    #[TestWith(['%', 'kichwa-es'])]
    #[TestWith(['_', 'kichwa-es'])]
    #[TestWith(['\\', 'kichwa-es'])]
    #[TestWith(['%', 'es-kichwa'])]
    #[TestWith(['_', 'es-kichwa'])]
    #[TestWith(['\\', 'es-kichwa'])]
    public function test_search_treats_pattern_characters_as_literal_text_and_ranks_exact_match_first(string $word, string $direction): void
    {
        Diccionario::create(['kichwa' => 'abc', 'español' => 'Sin coincidencia']);
        Diccionario::create(['kichwa' => $word.'abc', 'español' => 'Parcial']);
        $exact = Diccionario::create(['kichwa' => $word, 'español' => 'Exacta']);
        if ($direction === 'es-kichwa') {
            Diccionario::whereKey($exact->id)->update(['español' => $word]);
            Diccionario::where('kichwa', $word.'abc')->update(['español' => $word.'abc']);
        }

        $this->getJson('/api/diccionario/buscar?'.http_build_query(['q' => $word, 'direccion' => $direction]))->assertOk()->assertJsonPath('total', 2)->assertJsonPath('data.0', ['id' => $exact->id, 'kichwa' => $word, 'español' => $direction === 'es-kichwa' ? $word : 'Exacta']);
    }

    public function test_search_is_paginated_at_twenty_and_blank_query_only_suggests_five(): void
    {
        foreach (range(1, 25) as $i) {
            Diccionario::create(['kichwa' => '[DEMO] código '.$i, 'español' => '[DEMO] entrada '.$i]);
        }
        $this->getJson('/api/diccionario/buscar?q=codigo&direccion=kichwa-es')->assertOk()->assertJsonCount(20, 'data')->assertJsonPath('total', 25)->assertJsonPath('last_page', 2);
        $this->getJson('/api/diccionario/buscar?q=codigo&direccion=kichwa-es&page=2')->assertOk()->assertJsonCount(5, 'data');
        $this->getJson('/api/diccionario/buscar?q=&direccion=kichwa-es')->assertOk()->assertJsonCount(5, 'data');
    }

    public function test_csv_import_is_admin_only_atomic_and_preserves_existing_duplicates(): void
    {
        $csv = "kichwa,español\n[DEMO] código,[DEMO] entrada\n";
        Sanctum::actingAs(Usuario::factory()->create());
        $this->postJson('/api/admin/diccionario/import', ['file' => UploadedFile::fake()->createWithContent('entrada.csv', $csv)])->assertForbidden();
        Sanctum::actingAs(Usuario::factory()->administrador()->create());
        $this->postJson('/api/admin/diccionario/import', ['file' => UploadedFile::fake()->createWithContent('entrada.csv', $csv)])->assertCreated()->assertJsonPath('inserted', 1);
        $this->postJson('/api/admin/diccionario/import', ['file' => UploadedFile::fake()->createWithContent('entrada.csv', $csv)])->assertCreated()->assertJsonPath('skipped', 1);
        $this->postJson('/api/admin/diccionario/import', ['file' => UploadedFile::fake()->createWithContent('entrada.csv', "kichwa,español\n[DEMO] otro,entrada\n,inválida\n")])->assertUnprocessable()->assertJsonValidationErrors('file');
        $this->assertDatabaseCount('diccionario', 1);
        $this->assertDatabaseHas('diccionario', ['kichwa' => '[DEMO] código', 'español' => '[DEMO] entrada']);
    }
